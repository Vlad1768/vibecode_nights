const HOW_SCORED = 'Десять критериев, уровни от 0 до 3 и итог из 100. Для всех характеров действуют одинаковые веса и требования к доказательствам. Меняются манера разговора и фокус вопросов.';

export function createPersonaCatalog(baseContent) {
  return new Map(DEFINITIONS.map((p) => {
    const content = validateContent({
      ...baseContent,
      persona: {
        id: p.id, name: p.name, title: p.title, trait: p.trait, focus: p.focus,
        intro: `${p.who} ${p.behavior} В фокусе: ${p.focus.toLocaleLowerCase('ru')}.`,
        howScored: HOW_SCORED,
        character: `${p.who} Хочет: ${p.wants} Боится: ${p.fears} Вложится: ${p.invests} Никогда не вложится: ${p.never} Манера: ${p.behavior} Критикует проект, а не человека.`,
      },
      slots: [...baseContent.slots.slice(0, 4), p.slot],
    });
    return [p.id, content];
  }));
}

export function selectedPersonaView(content) {
  return {
    ...personaView(content),
    trait: content.persona.trait || 'Требовательный инвестор',
    focus: content.persona.focus || content.slots[4].topic,
  };
}
