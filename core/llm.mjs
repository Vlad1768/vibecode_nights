  'Конкретный клиент, его проблема, нынешний способ решения и свидетельства пользы продукта. Описание идеи само по себе не доказывает наличие проблемы.',
  'Кто платит, за что, сколько и как часто. Подписка без цены и плательщика — лишь заявленная модель; отличай предполагаемую цену от фактической оплаты.',
  'Сегмент, реальные альтернативы клиента, сравнение и обоснование доступного рынка. Не придумывай конкурентов. «Конкурентов нет» не подтверждает анализ; «1% огромного рынка» не подтверждает спрос.',
  'Связь выручки, затрат, маржи и допущений расчёта. Одна цена или желаемая выручка не заменяет финансовую модель. Оценивай согласованность расчёта по сообщённым данным.',
