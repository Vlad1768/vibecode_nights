  'Состоявшиеся оплаты, период, число клиентов и повторяемость. Интерес, регистрация пользователя, LOI и бесплатный пилот не называй продажами. Уровень 3 нельзя обосновать обещанием оплатить, будущим планом или отрицанием продаж. Если оплат нет, объясни, какие другие данные есть и чего они ещё не доказывают.',
  'Конкретный существенный риск проекта, способ его проверки или снижения и результат проверки, если он уже получен. Общий список возможных бед не заменяет проверку главного риска.',
  'На какой период построены расчёты и план: этапы, сроки и допущения. Не требуй необоснованный многолетний прогноз от ранней идеи.',
  'Конкретное отличие от названных альтернатив и его ценность для клиента. «Лучше», «удобнее», «у нас ИИ» сами по себе не доказывают преимущество.',
  'Зачем проекту ресурсы, какой проверяемый результат они дадут и чем подтверждается способность его достичь. Одного размера желаемых инвестиций недостаточно.',
