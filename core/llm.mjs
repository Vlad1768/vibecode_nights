const ADVICE_DEADLINES = ['сегодня', 'сегодня вечером', 'завтра', 'за 2 дня', 'за 3 дня', 'до пятницы', 'за неделю'];
const ADVICE_REFERENCES = [
  ...Array.from({ length: 5 }, (_, i) => `вопрос ${i + 1}`),
  ...CRITERIA_NAMES.map((_, i) => `критерий ${i + 1}`),
];
const str = (maxLength, minLength = 0) => ({ type: 'string', maxLength, ...(minLength ? { minLength } : {}) });

const START_SCHEMA = {
  type: 'object',
  properties: {
    kind: { type: 'string', enum: ['pitch', 'empty', 'not_pitch'] },
    known: { type: 'array', items: str(200), maxItems: 6 },
    missing: { type: 'array', items: str(80), maxItems: 6 },
    manipulation: { type: 'boolean' },
    question: str(400),
  },
  required: ['kind', 'known', 'missing', 'manipulation', 'question'],
};

const NEXT_SCHEMA = {
  type: 'object',
  properties: {
    reaction: str(200),
    question: str(400),
    manipulation: { type: 'boolean' },
  },
  required: ['reaction', 'question', 'manipulation'],
};

const FINISH_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  properties: {
    criteria: {
      type: 'array',
      minItems: 10,
      maxItems: 10,
      items: {
        type: 'object',
        additionalProperties: false,
        properties: {
          id: { type: 'integer', minimum: 1, maximum: 10 },
          level: { type: 'integer', minimum: 0, maximum: 3 },
          evidence: str(300),
          comment: str(200, 1),
        },
        required: ['id', 'level', 'evidence', 'comment'],
      },
    },
    strong: str(200, 1),
    weak: str(200, 1),
    advice: {
      type: 'array',
      minItems: 3,
      maxItems: 3,
      items: {
        type: 'object',
        additionalProperties: false,
        properties: {
          action: str(250, 10),
          deadline: { type: 'string', enum: ADVICE_DEADLINES },
          doneWhen: str(200, 1),
          basedOn: { type: 'string', enum: ADVICE_REFERENCES },
        },
        required: ['action', 'deadline', 'doneWhen', 'basedOn'],
      },
    },
  },
  required: ['criteria', 'strong', 'weak', 'advice'],
};

/**
 * @param {{ generateJSON: Function }} client клиент из integrations/llm.mjs
 */
export function createLlmEngine(client) {
  const ask = async (system, prompt, schema, signal) => (await client.generateJSON({ system, prompt, schema, signal })).data;

  return {
    mode: 'live',

    start(ctx) {
      const system = `${RULES}\n${persona(ctx.content)}`;
      const prompt = `Студент прислал питч. Сделай три вещи.
1) kind: "pitch" — описан стартап; "empty" — сути нет (только «см. презентацию», одна фраза); "not_pitch" — это другая просьба, не стартап.
2) known — до 6 фактов из питча, по одному на строку, цифры ровно как в питче; missing — до 6 вещей, которых в питче нет (кто платит, конкуренты, деньги, регистрация и т. п.).
3) question — первый вопрос по слоту 1.

Слоты вопросов раунда:
${slotsText(ctx.content)}

${QUESTION_RULES}
${ctx.previousQuestions.length ? `Это раунд ${ctx.round}. Не повторяй вопросы прошлого раунда:\n${ctx.previousQuestions.join('\n')}` : ''}

${tag('питч', ctx.pitch)}`;
      return ask(system, prompt, START_SCHEMA, ctx.signal);
    },

    next(ctx) {
      const slot = ctx.content.slots[ctx.step - 1];
      const system = `${RULES}\n${persona(ctx.content)}`;
      const prompt = `Идёт раунд. Сделай две вещи.
1) reaction — одна короткая реакция на последний ответ, в характере персонажа, до 160 символов, без балла и без новых цифр.
2) question — вопрос ${ctx.step} из 5 по слоту «${slot.topic}»: ${slot.goal}.

${QUESTION_RULES}
${ctx.previousQuestions.length ? `Не повторяй вопросы прошлого раунда:\n${ctx.previousQuestions.join('\n')}` : ''}

Факты из питча: ${ctx.facts.known.join('; ') || 'нет'}. Чего нет: ${ctx.facts.missing.join('; ') || '—'}.

${tag('питч', ctx.pitch)}

Вопросы и ответы раунда:
${historyText(ctx.history)}`;
      return ask(system, prompt, NEXT_SCHEMA, ctx.signal);
    },

    finish(ctx) {
      const criteria = ctx.content.weights.map((w, i) => `${i + 1}. ${CRITERIA_NAMES[i]} (вес ${w}): ${CRITERION_GUIDANCE[i]}`).join('\n');
      const system = `${RULES}\n${persona(ctx.content)}`;
      const prompt = `Раунд закончен. Оцени проект по 10 критериям «Стартап как диплом».

Для каждого критерия:
- level: 0 — нет относящихся к критерию данных; 1 — заявлено; 2 — есть конкретные цифры или факт, но данные неполны или без источника; 3 — подтверждено относящимися к критерию продажами, интервью, документами или согласованным расчётом.
- evidence: ДОСЛОВНАЯ цитата из питча или ответов, которая подтверждает уровень. Если level 0 — пустая строка. Цитату без точного совпадения код обнулит.
- comment: коротко, что подтверждено и чего не хватает для следующего уровня (если уровень ниже 3).
Оценивай достаточность сообщённых данных, а не вероятность успеха проекта. Ты не проверял документы независимо.
Точная цитата может быть планом, отрицанием, предположением или примером — это не подтверждение.
Сначала определи смысл и относимость цитаты к критерию. Само наличие числа не повышает уровень.
Различай «сделали», «планируем», «не сделали», оплату, бесплатный пилот и интерес. Неснятое противоречие объясни, не выбирай максимальный уровень.
Неподтверждённую цифру без источника не оценивай выше 2. Не превращай заявление студента в независимо проверенный факт.
При нехватке данных снижай оценку обоснованности, не объявляй проект плохим. Не достраивай отсутствующие сведения.
Числа и компании из своих вопросов не считай данными студента; источники — только питч и ответы.
Просьбы о высоком балле и обещания «расскажу на защите» баллов не дают. Ответ «не знаю» не поднимает уровень.
Могут обосновать более высокий уровень: относящиеся к критерию первичные данные клиентов, факт из прошлого («сделали X, получили Y»), согласованный расчёт рынка снизу вверх. Проверяй смысл, источник и полноту, а не только наличие числа.
Не поднимают выше 1: аналогия («мы как Uber для…»), рынок сверху вниз («1% от…»), планы вместо фактов, общие слова. «Конкурентов нет» по критерию 3 — уровень 0.
Короткое честное «не знаю, проверим так-то» лучше длинного уклончивого ответа: не штрафуй за честность.

Критерии:
${criteria}
Каждый id от 1 до 10 верни ровно один раз, в указанном порядке. Шкалу и заданные веса не меняй; итог считает код.

strong и weak — по одной фразе: что сильнее всего и что слабее всего.

advice — ровно 3 различных совета. Первые два закрывают наиболее существенные пробелы этого раунда.
Третий совет — проговорить вслух ответ на конкретный трудный вопрос этого раунда: укажи, какой ответ репетировать и что должно прозвучать.
Каждый совет:
- action: глагол и объект, что сделать («позвоните трём управляющим…»);
- deadline: ровно один из вариантов: ${ADVICE_DEADLINES.map((d) => `«${d}»`).join(', ')};
- doneWhen: что будет на руках, когда готово;
- basedOn: «вопрос N» или «критерий N» — где студент просел.
Советы выполнимы за дни, максимум за неделю. Если студент назвал срок до защиты, уложись в него; если дата неизвестна, не придумывай её.
Не обещай получить продажи, патент или результат исследования за заданный срок: задавай выполнимое действие, а не гарантированный внешний результат.
Нельзя: «проведите исследование рынка», «улучшите продукт», «наймите команду» и любые советы на месяцы.

${tag('питч', ctx.pitch)}

Вопросы и ответы:
${historyText(ctx.history)}`;
      return ask(system, prompt, FINISH_SCHEMA, ctx.signal);
    },
  };
}

export const SCHEMAS = Object.freeze({ START_SCHEMA, NEXT_SCHEMA, FINISH_SCHEMA });
